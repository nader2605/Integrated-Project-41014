"""Build the project scene from the unmodified, licensed ROBOTIS Waffle Pi model."""
from copy import deepcopy
import math
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def build():
    original = ET.parse(ROOT / 'vendor/robotis_tb3/turtlebot3_waffle_pi.xml').getroot()
    room = ET.parse(ROOT / 'scene.xml').getroot()
    original.set('model', 'Track A TurtleBot3 Waffle Pi')
    original.find('compiler').set('meshdir', 'vendor/robotis_tb3/assets')
    original.find('option').set('timestep', '0.002')
    original.find('option').set('gravity', '0 0 -9.81')
    original.insert(0, ET.Comment('Project adaptation of ROBOTIS TurtleBot3; see vendor/robotis_tb3/SOURCE.md and LICENSE. Generated by scripts/build_turtlebot_scene.py.'))
    original.append(deepcopy(room.find('visual')))
    for asset in room.find('asset'):
        original.find('asset').append(deepcopy(asset))
    world = original.find('worldbody')
    base = world.find("body[@name='base']")
    base.set('pos', '-2.05 -1.35 0.002')
    robot = room.find(".//body[@name='robot']")
    for child in room.find('worldbody'):
        if child is not robot:
            world.append(deepcopy(child))
    # Elevated project camera mast preserves full marker visibility at docking.
    camera = deepcopy(robot.find('camera'))
    camera.set('pos', '0.18 0 0.55')
    base.append(camera)
    ET.SubElement(base, 'geom', name='camera_mast', type='capsule',
                  **{'fromto': '0.08 0 0.14 0.08 0 0.54', 'size': '0.008',
                     'rgba': '0.3 0.4 0.5 1', 'contype': '0', 'conaffinity': '0', 'mass': '0'})
    sensors = ET.SubElement(original, 'sensor')
    ET.SubElement(base,'site',name='imu_site',pos='0 0 0.12',size='0.004')
    ET.SubElement(sensors,'gyro',name='imu_gyro',site='imu_site')
    for i in range(72):
        angle = math.radians(-180 + 5*i)
        ET.SubElement(base, 'site', name=f'lidar_{i}', pos='0 0 0.23',
                      zaxis=f'{math.cos(angle)} {math.sin(angle)} 0', size='0.004')
        ET.SubElement(sensors, 'rangefinder', name=f'range_{i}', site=f'lidar_{i}')
    # Tune the wheel velocity servos for the 50 Hz outer controller.
    servo = original.find(".//default[@class='wheel']/velocity")
    servo.set('kv', '0.2')
    servo.set('forcerange', '-0.2 0.2')
    servo.set('forcelimited', 'true')
    wheel_joint = original.find(".//default[@class='wheel']/joint")
    wheel_joint.set('frictionloss', '0.001')
    wheel_joint.set('armature', '0.0001')
    # Smooth collision tyres avoid convex STL faceting in rolling contact.
    for wheel in base.findall('body'):
        collision = wheel.find("geom[@class='collision']")
        if collision is not None:
            collision.attrib.clear()
            collision.attrib.update(type='cylinder', size='0.033 0.009',
                                    rgba='0.2 0.2 0.2 0', group='3',
                                    friction='1.0 0.005 0.0001', condim='4')
    tree = ET.ElementTree(original)
    ET.indent(tree, space='  ')
    target = ROOT / 'scene_turtlebot.xml'
    tree.write(target, encoding='unicode')
    return target


if __name__ == '__main__':
    print(build())
